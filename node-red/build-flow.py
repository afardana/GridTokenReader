"""Builds the GridTokenReader Node-RED tab.

Usage: python3 build-flow.py <influx_config_id|new> <org> <bucket> > flow.json

With influx_config_id "new", an InfluxDB v2 config node (http://127.0.0.1:8086) is
included; set its token in the Node-RED editor after importing.

Pipeline:
  POST /gridtoken/ingest (JPEG, behind the nginx token gate, see docs/NGINX.md)
    -> save frame -> recogniser (Python, exec) -> plausibility -> InfluxDB
  POST /gridtoken/reading (JSON {"kwh": ...}) -> InfluxDB pln_prepaid

Tab environment variables (edit on the tab):
  GRIDTOKEN_FRAMES         frame directory (default /var/lib/gridtoken/frames)
  GRIDTOKEN_RECOGNISER     directory with gridtoken_recognise.py and profiles/<device>.json
  GRIDTOKEN_PUBLISH        "true" = accepted camera readings go to pln_prepaid;
                           otherwise shadow mode (only gridtoken_recognition is written)
  GRIDTOKEN_MAX_KW         supply limit for the plausibility check (25 A x 230 V = 5.75)
  GRIDTOKEN_TOPUP_MIN_KWH  smallest rise treated as a token top-up
  GRIDTOKEN_TELEGRAM_CHAT  chat id for alerts (empty = no alerts); the "Telegram"
                           http request node needs your bot URL
"""
